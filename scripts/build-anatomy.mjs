// Figure: an actual laptop and phone, with a quiet illustrated data route.
// Parts: laptop deck, lip, trackpad, keyboard recess, 44 keys, two hinges,
// display shell, rim, camera, glass and file; phone shell, rim, glass,
// speaker, camera, two volume keys, power key and home indicator.
import { writeFileSync } from 'node:fs';
import * as k from './anatomy/iso-kit.mjs';
const P=k.fitProjection([[-155,-40,0],[-155,-40,95],[-8,57,0],[150,-5,0],[150,-5,90]],720,350,{pad:58,azimuth:70,elevation:22});
const plan=(x,y,w,d,r=1)=>({x,y,w,d,r});
const slab=(p,z,h,tone='mid')=>k.solidSvg(k.slabOf(p,z,h,P,6,Math.min(.6,h/3)),{tone});
const rect=(x,y,w,h,r,fill,stroke='none',sw=.4)=>`<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${r}" fill="${fill}" stroke="${stroke}" stroke-width="${sw}"/>`;
const line=(d,color='#969c94',width=.6)=>`<path d="${d}" fill="none" stroke="${color}" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round"/>`;
const file=(x,y,w=16,h=21)=>`<path d="M${x+2} ${y}H${x+w-5}L${x+w} ${y+5}V${y+h-2}Q${x+w} ${y+h} ${x+w-2} ${y+h}H${x+2}Q${x} ${y+h} ${x} ${y+h-2}V${y+2}Q${x} ${y} ${x+2} ${y}Z" fill="#f6f7f3" stroke="#d2d8ce" stroke-width=".45"/>${line(`M${x+w-5} ${y}V${y+5}H${x+w}`,'#a2ac9e',.5)}${line(`M${x+4} ${y+11}H${x+w-4}M${x+4} ${y+15}H${x+w-6}`,'#9ea897',.65)}`;
const at=p=>k.iso(p,P);
const deck=plan(-153,-34,141,91,4);
let laptop=`<path class="iso-halo" d="${k.haloOf(deck,-2,2,P)}"/>`;
laptop+=slab(deck,0,3.2,'lo');
laptop+=k.lineSvg(k.sideSeam(deck,1.1,P,6),{tone:'faint'});
laptop+=slab(plan(-146,-23,127,42,2),3.2,.35,'lo');
for(let row=0;row<4;row++)for(let col=0;col<11;col++)laptop+=slab(plan(-143+col*11,-20+row*9,8.8,6.4,.9),3.55,.75,'lo');
laptop+=slab(plan(-105,15,49,4.8,1),3.55,.75,'lo');
laptop+=slab(plan(-108,27,51,22,2),3.2,.25,'lo');
for(const x of [-137,-36])laptop+=slab(plan(x,-35,17,5,1),3.2,2.8,'mid');
// Display faces are in the same world camera as the physical deck.
const display=k.sideMatrix([-152,-33],91,P,'left');
const back=k.sideMatrix([-152,-36],92,P,'left');
laptop+=`<g transform="${back}">${rect(0,0,140,85,4,'#81887e','#777f73')}</g>`;
laptop+=`<g transform="${display}">${rect(0,0,140,85,4,'#252c25','#5f685b')}${rect(3.5,3.5,133,76,2,'#182219','#0d170f')}${rect(66,1.4,8,.6,.3,'#9ca395')}<circle cx="70" cy="2" r=".55" fill="#0a0e0a"/>${rect(8,8,124,65,1.5,'#222e23')}${rect(12,12,32,2,1,'#6c7c66')}${rect(12,17,18,1,0.5,'#465840')}${rect(48,25,44,38,3,'#2e3b2d','#4e6147')}${file(62,30,16,20)}<text x="70" y="57" text-anchor="middle" font-family="Arial,sans-serif" font-size="4" fill="#dce4d5">notes.pdf</text>${rect(48,67,44,1.6,.8,'#4d5c46')}</g>`;
// A rounded metal phone with a separate rim; screen graphics are clipped.
let phone='';
const phoneBack=k.sideMatrix([99,-3],83,P,'left');
const phoneFace=k.sideMatrix([99,1],82,P,'left');
phone+=`<ellipse cx="${at([120,0,0])[0]}" cy="${at([120,0,0])[1]+3}" rx="40" ry="8" fill="#8f9886" opacity=".12"/>`;
phone+=`<g transform="${phoneBack}">${rect(0,0,44,83,6,'#929a8b','#7e8976',.5)}</g>`;
phone+=`<g transform="${phoneFace}">${rect(0,0,44,82,6,'#384332','#69775e',.5)}${rect(1.2,1.2,41.6,79.6,5,'#172013','#111a0f',.5)}${rect(3.5,4,37,73,3.5,'#edf1e8')}${rect(15,5.5,14,3,1.5,'#1f281a')}<circle cx="26.7" cy="7" r=".65" fill="#65725a"/>${rect(17,74.3,10,1.1,.55,'#718166')}${line('M6 17H38','#d6dece',.35)}<text x="7" y="14" font-family="Arial,sans-serif" font-size="3.6" fill="#3c5131">thread.</text></g>`;
// Physical side buttons sit on the outer rim rather than floating beside it.
for(const [z,h] of [[65,5],[57,5]])phone+=slab(plan(98.3,-.4,.7,1.5,.25),z,h,'lo');
phone+=slab(plan(143,-.4,.7,1.5,.25),57,11,'lo');
const start=at([-12,-33,40]),end=at([99,1,40]);
const control1=[start[0]+(end[0]-start[0])*.38,start[1]-30];
const control2=[start[0]+(end[0]-start[0])*.62,end[1]-30];
const route=`M${start.join(' ')}C${control1.join(' ')} ${control2.join(' ')} ${end.join(' ')}`;
const geometry={devices:laptop+phone,phoneFace,route,curve:[start,control1,control2,end],source:at([-82,-32,42]),laptopLabel:at([-85,56,-14]),phoneLabel:at([121,3,-15])};
writeFileSync(new URL('../frontend/src/anatomy/art.ts',import.meta.url),`// Generated by scripts/build-anatomy.mjs.\nexport const art = ${JSON.stringify(geometry)} as const;\n`);
console.log('Generated laptop + phone illustration (720 × 350).');
